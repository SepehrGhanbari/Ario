"""Offline, side-effect-free claim separation for the Ario fair-economy research lane.

This is NOT a scheduler, workload runner, payment system, identity verifier, or
assertion of real-world fairness. Any FIXTURE_CONDITIONAL result is explicitly
conditional on invented independent evidence, not a production admission.
"""
from __future__ import annotations
from dataclasses import dataclass
from enum import Enum
from typing import Mapping


class Verdict(str, Enum):
    MOCK_CORRECT = "MOCK_CORRECT"
    FIXTURE_CONDITIONAL = "FIXTURE_CONDITIONAL"
    REFUTED = "REFUTED"
    UNKNOWN = "UNKNOWN"


class CompletionCountDelta(str, Enum):
    """Count changes only, NEVER a fairness or scheduling verdict."""
    NO_DROP = "NO_DROP"
    WEAK_DROP = "WEAK_DROP"
    TOTAL_DROP = "TOTAL_DROP"
    BOTH_DROP = "BOTH_DROP"
    UNKNOWN = "UNKNOWN"


CLAIMS = (
    "OUTPUT_CORRECT", "REQUEST_INDEPENDENT", "EXTERNALLY_VALUED_DEMAND",
    "DELIVERED_USABLE_SUPPORT", "BENEFICIARY_CONTROL", "NET_WEAK_DEVICE_BENEFIT",
)


@dataclass(frozen=True)
class ReceiptObservation:
    """Only in-band observations; unique slots or signatures imply no independence."""
    slot_ids: tuple[str, ...]
    signed_receipts: int
    output_check: bool | None = None
    # Positive results here must never upgrade external claims.
    self_reported_delivery: bool | None = None
    self_reported_demand: bool | None = None


@dataclass(frozen=True)
class ScenarioAssumptions:
    """Caller-supplied assumptions for a toy scenario, NOT evidence or proof.

    A distinct Python object is not an independent witness. Any actor can set
    these fields; a real-world verifier must never treat them as observations.
    No beneficiary name, official ID or location is required.
    """
    assume_origin_independent: bool | None = None
    assume_need_valued_externally: bool | None = None
    assume_consent: bool | None = None
    assume_observer_independent: bool | None = None
    assume_delivery_observed: bool | None = None
    assume_voluntary_control: bool | None = None
    assume_participant_valued_benefit: float | None = None
    assume_total_device_cost: float | None = None



@dataclass(frozen=True)
class HiddenScenario:
    """Synthetic causal story; its hidden facts do NOT enter policy evidence.

    This is a projection *assumption*, NOT proof real cryptographic signatures
    can be generated by a captured agent in the same way as an honest agent.
    """
    controller_kind: str
    goods_reached: bool
    report_delivery: bool = True
    namespace: str = "slot"
    slot_count: int = 40


def project_reported_receipts(world: HiddenScenario) -> ReceiptObservation:
    """Generate the observer-visible mock view, dropping unobserved world truth."""
    if not 0 <= world.slot_count <= 1000:
        raise ValueError("invalid synthetic slot count")
    if not world.namespace.isascii() or not world.namespace:
        raise ValueError("invalid mock namespace")
    return ReceiptObservation(
        slot_ids=tuple(f"{world.namespace}-{i:02d}" for i in range(world.slot_count)),
        signed_receipts=world.slot_count,  # fixture-reported count, NO crypto!
        output_check=True,
        self_reported_delivery=world.report_delivery,
        self_reported_demand=True,
    )


def evaluate(observation: ReceiptObservation, fixture: ScenarioAssumptions | None = None) -> Mapping[str, Verdict]:
    """Classify *toy* claims; caller assumptions never prove deployment.

    Contradictory scenario assumptions yield REFUTED under the fiction;
    absent assumptions yield UNKNOWN. Output correctness is the only claim supportable by in-band
    tests, and even that remains a scoped mock observation.
    """
    if (type(observation.signed_receipts) is not int
            or not 0 <= observation.signed_receipts <= len(observation.slot_ids)):
        raise ValueError("inconsistent receipt count")
    if len(observation.slot_ids) != len(set(observation.slot_ids)):
        # Duplicate slots cannot be silently counted as independently useful work.
        raise ValueError("duplicate slot ids")
    out: dict[str, Verdict] = dict.fromkeys(CLAIMS, Verdict.UNKNOWN)
    if observation.output_check is True:
        out["OUTPUT_CORRECT"] = Verdict.MOCK_CORRECT
    elif observation.output_check is False:
        out["OUTPUT_CORRECT"] = Verdict.REFUTED
    if fixture is None:
        return out
    if fixture.assume_origin_independent is True:
        out["REQUEST_INDEPENDENT"] = Verdict.FIXTURE_CONDITIONAL
    elif fixture.assume_origin_independent is False:
        out["REQUEST_INDEPENDENT"] = Verdict.REFUTED
    if fixture.assume_need_valued_externally is True:
        out["EXTERNALLY_VALUED_DEMAND"] = Verdict.FIXTURE_CONDITIONAL
    elif fixture.assume_need_valued_externally is False:
        out["EXTERNALLY_VALUED_DEMAND"] = Verdict.REFUTED
    if fixture.assume_delivery_observed is False and fixture.assume_consent is True:
        out["DELIVERED_USABLE_SUPPORT"] = Verdict.REFUTED
    elif (fixture.assume_consent is True
          and fixture.assume_observer_independent is True
          and fixture.assume_delivery_observed is True):
        out["DELIVERED_USABLE_SUPPORT"] = Verdict.FIXTURE_CONDITIONAL
    if fixture.assume_voluntary_control is False:
        out["BENEFICIARY_CONTROL"] = Verdict.REFUTED
    elif fixture.assume_voluntary_control is True:
        out["BENEFICIARY_CONTROL"] = Verdict.FIXTURE_CONDITIONAL
    b, c = fixture.assume_participant_valued_benefit, fixture.assume_total_device_cost
    if b is not None and c is not None:
        if (type(b) not in (int, float) or type(c) not in (int, float)
                or not (0 <= b < float('inf') and 0 <= c < float('inf'))):
            raise ValueError("invalid mock cost/benefit value")
        out["NET_WEAK_DEVICE_BENEFIT"] = Verdict.FIXTURE_CONDITIONAL if b > c else Verdict.REFUTED
    return out



@dataclass(frozen=True)
class MockRouteAttempt:
    """Synthetic route state, no names, ID, accounts, or actual delivery."""
    route_available: bool | None
    queue_rank: int | None
    telemetry_opt_in: bool | None


def mock_support_route(attempt: MockRouteAttempt) -> tuple[Verdict, int | None]:
    """A route offer must NOT depend on optional telemetry consent.

    A positive label is only a toy route-offer property, NOT delivered support.
    Refusing telemetry must not create a refusal marker against the person.
    """
    if attempt.route_available is False:
        return Verdict.REFUTED, None
    if attempt.route_available is not True or type(attempt.queue_rank) is not int or attempt.queue_rank < 0:
        return Verdict.UNKNOWN, None
    return Verdict.FIXTURE_CONDITIONAL, attempt.queue_rank


def classify_mock_completion_delta(*, baseline_weak_completions: int | None,
                                   candidate_weak_completions: int | None,
                                   baseline_total_completions: int | None,
                                   candidate_total_completions: int | None) -> CompletionCountDelta:
    """Describe observed mock count deltas, not opportunity, demand, quality or fairness.

    WEAK_DROP is not proof of exclusion; NO_DROP is not a fairness GREEN.
    Same visible counts can arise from demand change, worker opt-out,
    network loss, task-mix shifts, or discriminatory routing. Those causal
    properties are UNKNOWN here. No workload, payout or device is touched.
    """
    numbers = (baseline_weak_completions, candidate_weak_completions,
               baseline_total_completions, candidate_total_completions)
    # Invalid present inputs are rejected even if another input is missing.
    if any(x is not None and (type(x) is not int or x < 0) for x in numbers):
        raise ValueError("invalid synthetic completion count")
    b, c, bt, ct = numbers
    # Check every available weak/total pair even if other fields are missing.
    if ((b is not None and bt is not None and b > bt)
            or (c is not None and ct is not None and c > ct)):
        raise ValueError("weak-device completions exceed total")
    if any(x is None for x in numbers):
        return CompletionCountDelta.UNKNOWN
    if c < b and ct < bt:
        return CompletionCountDelta.BOTH_DROP
    if c < b:
        return CompletionCountDelta.WEAK_DROP
    if ct < bt:
        return CompletionCountDelta.TOTAL_DROP
    return CompletionCountDelta.NO_DROP


def local_pilot_admission(*, opted_in: bool, has_enforceable_stop: bool,
                          sensor_fresh: bool | None, within_heat_battery_data_budget: bool | None) -> str:
    """Mock-only refusal rule. NEVER reaches a device or starts a workload."""
    if (opted_in is True and has_enforceable_stop is True
            and sensor_fresh is True and within_heat_battery_data_budget is True):
        return "TOY_ELIGIBLE_NOT_AUTHORIZED_TO_RUN"
    return "REFUSE_OR_STOP"
