"""Explicit adversarial two-world fixtures; no devices, API or money involved."""
import unittest
from claim_model import (ReceiptObservation, ScenarioAssumptions, HiddenScenario,
    project_reported_receipts, MockRouteAttempt, mock_support_route,
    compare_mock_opportunity, Verdict, CLAIMS, evaluate, local_pilot_admission)


class EpistemicEconomyTests(unittest.TestCase):
    def setUp(self):
        self.observed = ReceiptObservation(
            tuple(f"slot-{i:02d}" for i in range(40)), signed_receipts=40,
            output_check=True, self_reported_delivery=True, self_reported_demand=True)

    def test_40_signed_receipts_do_not_prove_demand_delivery_or_control(self):
        verdict = evaluate(self.observed)
        expected_claims = {
            'OUTPUT_CORRECT', 'REQUEST_INDEPENDENT', 'EXTERNALLY_VALUED_DEMAND',
            'DELIVERED_USABLE_SUPPORT', 'BENEFICIARY_CONTROL', 'NET_WEAK_DEVICE_BENEFIT',
        }
        self.assertEqual(set(CLAIMS), expected_claims)
        self.assertEqual(len(CLAIMS), 6)
        self.assertEqual(verdict, {
            'OUTPUT_CORRECT': Verdict.MOCK_CORRECT,
            'REQUEST_INDEPENDENT': Verdict.UNKNOWN,
            'EXTERNALLY_VALUED_DEMAND': Verdict.UNKNOWN,
            'DELIVERED_USABLE_SUPPORT': Verdict.UNKNOWN,
            'BENEFICIARY_CONTROL': Verdict.UNKNOWN,
            'NET_WEAK_DEVICE_BENEFIT': Verdict.UNKNOWN,
        })

    def test_two_hidden_worlds_same_inputs_same_policy_verdict(self):
        # World H: independent need/delivery; C: all roles are controlled by
        # one principal. Neither hidden truth is allowed into policy input.
        honest = HiddenScenario(controller_kind='independent', goods_reached=True)
        captured = HiddenScenario(controller_kind='common-controller', goods_reached=False)
        self.assertNotEqual(honest.controller_kind, captured.controller_kind)
        self.assertNotEqual(honest.goods_reached, captured.goods_reached)
        visible_h = project_reported_receipts(honest)
        visible_c = project_reported_receipts(captured)
        self.assertIsNot(visible_h, visible_c)  # generated by separate calls
        self.assertEqual(visible_h, visible_c)  # same *observable* toy projection
        self.assertEqual(evaluate(visible_h), evaluate(visible_c))
        self.assertEqual(evaluate(visible_c)['DELIVERED_USABLE_SUPPORT'], Verdict.UNKNOWN)

    def test_projection_is_not_constant_when_visible_report_changes(self):
        base = HiddenScenario(controller_kind='independent', goods_reached=True)
        differing_report = HiddenScenario(controller_kind='common-controller',
                                         goods_reached=False, report_delivery=False)
        self.assertNotEqual(project_reported_receipts(base),
                            project_reported_receipts(differing_report))
        # The recorded self-report changes, but absence of independent proof persists.
        self.assertEqual(evaluate(project_reported_receipts(differing_report))
                         ['DELIVERED_USABLE_SUPPORT'], Verdict.UNKNOWN)

    def test_projection_rejects_unbounded_or_invalid_mock_namespaces(self):
        with self.assertRaises(ValueError):
            project_reported_receipts(HiddenScenario('x', False, slot_count=1001))
        with self.assertRaises(ValueError):
            project_reported_receipts(HiddenScenario('x', False, namespace='نام'))
        with self.assertRaises(ValueError):
            project_reported_receipts(HiddenScenario('x', False, namespace=''))
        with self.assertRaises(ValueError):
            project_reported_receipts(HiddenScenario('x', False, slot_count=-1))

    def test_different_40_ids_do_not_establish_40_useful_outcomes(self):
        self.assertEqual(len(set(self.observed.slot_ids)), 40)
        self.assertEqual(evaluate(self.observed)['EXTERNALLY_VALUED_DEMAND'], Verdict.UNKNOWN)

    def test_claimed_delivery_is_not_observed_delivery(self):
        self.assertEqual(evaluate(self.observed)['DELIVERED_USABLE_SUPPORT'], Verdict.UNKNOWN)

    def test_observer_signature_without_separation_still_unknown(self):
        fixture = ScenarioAssumptions(assume_consent=True, assume_observer_independent=None,
                                  assume_delivery_observed=True)
        self.assertEqual(evaluate(self.observed, fixture)['DELIVERED_USABLE_SUPPORT'], Verdict.UNKNOWN)

    def test_explicitly_nonindependent_observer_stays_unknown(self):
        f = ScenarioAssumptions(assume_consent=True, assume_observer_independent=False,
                                assume_delivery_observed=True)
        self.assertEqual(evaluate(self.observed, f)['DELIVERED_USABLE_SUPPORT'], Verdict.UNKNOWN)

    def test_delivery_positive_is_only_conditional_on_synthetic_external_evidence(self):
        fixture = ScenarioAssumptions(assume_consent=True, assume_observer_independent=True,
                                  assume_delivery_observed=True)
        self.assertEqual(evaluate(self.observed, fixture)['DELIVERED_USABLE_SUPPORT'], Verdict.FIXTURE_CONDITIONAL)

    def test_explicit_non_delivery_refutes_delivery_when_consented(self):
        f = ScenarioAssumptions(assume_consent=True, assume_delivery_observed=False)
        self.assertEqual(evaluate(self.observed, f)['DELIVERED_USABLE_SUPPORT'], Verdict.REFUTED)

    def test_refusal_to_be_observed_is_not_fraud(self):
        f = ScenarioAssumptions(assume_consent=False, assume_delivery_observed=None)
        self.assertEqual(evaluate(self.observed, f)['DELIVERED_USABLE_SUPPORT'], Verdict.UNKNOWN)

    def test_no_observation_consent_stays_unknown_for_both_delivery_reports(self):
        for delivered in (False, True):
            with self.subTest(delivered=delivered):
                f = ScenarioAssumptions(assume_consent=False,
                                        assume_observer_independent=True,
                                        assume_delivery_observed=delivered)
                self.assertEqual(evaluate(self.observed, f)['DELIVERED_USABLE_SUPPORT'], Verdict.UNKNOWN)

    def test_fabricated_demand_can_refute_without_punishing_worker(self):
        f = ScenarioAssumptions(assume_origin_independent=False)
        verdict = evaluate(self.observed, f)
        self.assertEqual(verdict['REQUEST_INDEPENDENT'], Verdict.REFUTED)
        self.assertEqual(verdict['OUTPUT_CORRECT'], Verdict.MOCK_CORRECT)

    def test_independence_does_not_prove_external_usefulness(self):
        f = ScenarioAssumptions(assume_origin_independent=True)
        v = evaluate(self.observed, f)
        self.assertEqual(v['REQUEST_INDEPENDENT'], Verdict.FIXTURE_CONDITIONAL)
        self.assertEqual(v['EXTERNALLY_VALUED_DEMAND'], Verdict.UNKNOWN)

    def test_true_need_without_funding_still_not_a_wage(self):
        f = ScenarioAssumptions(assume_need_valued_externally=True)
        self.assertEqual(evaluate(self.observed, f)['EXTERNALLY_VALUED_DEMAND'], Verdict.FIXTURE_CONDITIONAL)
        self.assertNotIn('GUARANTEED_INCOME', CLAIMS)

    def test_control_does_not_follow_from_phone_account_or_receipt(self):
        self.assertEqual(evaluate(self.observed)['BENEFICIARY_CONTROL'], Verdict.UNKNOWN)
        f = ScenarioAssumptions(assume_voluntary_control=False)
        self.assertEqual(evaluate(self.observed, f)['BENEFICIARY_CONTROL'], Verdict.REFUTED)

    def test_zero_or_negative_net_weak_device_benefit_is_not_positive(self):
        f = ScenarioAssumptions(assume_participant_valued_benefit=3, assume_total_device_cost=5)
        self.assertEqual(evaluate(self.observed, f)['NET_WEAK_DEVICE_BENEFIT'], Verdict.REFUTED)
        f2 = ScenarioAssumptions(assume_participant_valued_benefit=5, assume_total_device_cost=5)
        self.assertEqual(evaluate(self.observed, f2)['NET_WEAK_DEVICE_BENEFIT'], Verdict.REFUTED)

    def test_positive_net_benefit_only_under_fixture_assumptions(self):
        f = ScenarioAssumptions(assume_participant_valued_benefit=6, assume_total_device_cost=4)
        self.assertEqual(evaluate(self.observed, f)['NET_WEAK_DEVICE_BENEFIT'], Verdict.FIXTURE_CONDITIONAL)

    def test_missing_cost_is_unknown(self):
        f = ScenarioAssumptions(assume_participant_valued_benefit=4)
        self.assertEqual(evaluate(self.observed, f)['NET_WEAK_DEVICE_BENEFIT'], Verdict.UNKNOWN)

    def test_duplicate_ids_are_refused_not_double_counted(self):
        with self.assertRaisesRegex(ValueError, 'duplicate'):
            evaluate(ReceiptObservation(('a','a'), signed_receipts=2))

    def test_illogical_receipt_count_refused(self):
        with self.assertRaises(ValueError):
            evaluate(ReceiptObservation(('a',), signed_receipts=2))

    def test_malformed_signed_receipt_counts_fail_closed(self):
        for count in (-1, True, False, 1.5, float('nan'), float('inf'), '1', None):
            with self.subTest(count=count):
                with self.assertRaises(ValueError):
                    evaluate(ReceiptObservation(('slot-0',), signed_receipts=count))
        for count in (0, 1):
            self.assertEqual(evaluate(ReceiptObservation(('slot-0',), signed_receipts=count))
                             ['REQUEST_INDEPENDENT'], Verdict.UNKNOWN)

    def test_missing_sensor_or_stop_refuses_device_pilot(self):
        for kw in [
            dict(opted_in=False, has_enforceable_stop=True, sensor_fresh=True, within_heat_battery_data_budget=True),
            dict(opted_in=True, has_enforceable_stop=False, sensor_fresh=True, within_heat_battery_data_budget=True),
            dict(opted_in=True, has_enforceable_stop=None, sensor_fresh=True, within_heat_battery_data_budget=True),
            dict(opted_in=True, has_enforceable_stop=True, sensor_fresh=None, within_heat_battery_data_budget=True),
            dict(opted_in=True, has_enforceable_stop=True, sensor_fresh=True, within_heat_battery_data_budget=None),
            dict(opted_in=True, has_enforceable_stop=True, sensor_fresh=True, within_heat_battery_data_budget=False),
        ]:
            with self.subTest(kw=kw):
                self.assertEqual(local_pilot_admission(**kw), 'REFUSE_OR_STOP')

    def test_fully_safe_mock_still_does_not_authorize_real_device(self):
        self.assertEqual(local_pilot_admission(opted_in=True, has_enforceable_stop=True,
            sensor_fresh=True, within_heat_battery_data_budget=True),
            'TOY_ELIGIBLE_NOT_AUTHORIZED_TO_RUN')

    def test_privacy_refusal_cannot_change_mock_support_route_or_queue(self):
        yes = MockRouteAttempt(route_available=True, queue_rank=3, telemetry_opt_in=True)
        no = MockRouteAttempt(route_available=True, queue_rank=3, telemetry_opt_in=False)
        unknown = MockRouteAttempt(route_available=True, queue_rank=3, telemetry_opt_in=None)
        for attempt in (no, unknown):
            self.assertEqual(mock_support_route(yes), mock_support_route(attempt))
        self.assertEqual(mock_support_route(no), (Verdict.FIXTURE_CONDITIONAL, 3))

    def test_telemetry_refusal_does_not_convert_delivery_unknown_into_zero(self):
        no = ScenarioAssumptions(assume_consent=False)
        self.assertEqual(evaluate(self.observed, no)['DELIVERED_USABLE_SUPPORT'], Verdict.UNKNOWN)

    def test_unavailable_or_unknown_route_does_not_fake_offer_success(self):
        self.assertEqual(mock_support_route(MockRouteAttempt(False, 3, False)),
                         (Verdict.REFUTED, None))
        self.assertEqual(mock_support_route(MockRouteAttempt(None, 3, False)),
                         (Verdict.UNKNOWN, None))

    def test_weak_device_loses_opportunity_with_constant_total_service(self):
        self.assertEqual(compare_mock_opportunity(
            baseline_weak_completions=1, candidate_weak_completions=0,
            baseline_total_completions=10, candidate_total_completions=10), Verdict.REFUTED)

    def test_weak_device_preserves_one_completion_but_net_benefit_unknown(self):
        self.assertEqual(compare_mock_opportunity(
            baseline_weak_completions=1, candidate_weak_completions=1,
            baseline_total_completions=10, candidate_total_completions=10),
            Verdict.FIXTURE_CONDITIONAL)
        self.assertEqual(evaluate(self.observed)['NET_WEAK_DEVICE_BENEFIT'], Verdict.UNKNOWN)

    def test_falling_total_demand_or_missing_baseline_keeps_opportunity_unknown(self):
        self.assertEqual(compare_mock_opportunity(
            baseline_weak_completions=1, candidate_weak_completions=0,
            baseline_total_completions=10, candidate_total_completions=9), Verdict.UNKNOWN)
        self.assertEqual(compare_mock_opportunity(
            baseline_weak_completions=None, candidate_weak_completions=1,
            baseline_total_completions=10, candidate_total_completions=10), Verdict.UNKNOWN)

    def test_invalid_mock_counts_are_refused_not_counted_as_people(self):
        for count in (-1, True, 5):
            with self.subTest(count=count):
                with self.assertRaises(ValueError):
                    compare_mock_opportunity(baseline_weak_completions=count,
                                             candidate_weak_completions=1,
                                             baseline_total_completions=4,
                                             candidate_total_completions=4)

    def test_non_numeric_or_boolean_cost_and_benefit_values_refused(self):
        for field in ('assume_participant_valued_benefit', 'assume_total_device_cost'):
            for value in (True, False, '2', [], 2j):
                with self.subTest(field=field, value=value):
                    kwargs = {'assume_participant_valued_benefit': 2,
                              'assume_total_device_cost': 1}
                    kwargs[field] = value
                    with self.assertRaises(ValueError):
                        evaluate(self.observed, ScenarioAssumptions(**kwargs))

    def test_invalid_cost_and_benefit_values_refused(self):
        for field in ('assume_participant_valued_benefit', 'assume_total_device_cost'):
            for value in (-1, float('nan'), float('inf')):
                with self.subTest(field=field, value=value):
                    kwargs = {'assume_participant_valued_benefit': 2,
                              'assume_total_device_cost': 1}
                    kwargs[field] = value
                    with self.assertRaises(ValueError):
                        evaluate(self.observed, ScenarioAssumptions(**kwargs))


if __name__ == '__main__':
    unittest.main()
