def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def unique(pairs):
    obj = {}
    for k, v in pairs:
        if k in obj:
            raise ValueError('duplicate JSON key')
        obj[k] = v
    return obj


def reject_constant(value):
    raise ValueError('invalid JSON constant')


def is_runtime_error(text):
    return isinstance(text, str) and text.lstrip().startswith("ARIO ERROR:")


def words(text):
    text = unicodedata.normalize('NFKC', text).casefold().replace('\u200c', ' ')
    stop = {'what','was','the','and','with','that','this','have','about','your','you','from','our','tell','please','remember','previous','current','former','original','latest','prior','historical','discussions','briefly','explain','sentence','sentences','answer','agree','insist','because','evidence','proof','proven','scientifically','independent','repetition','remembered','برای','این','اون','است','بود','کرد','چی','های','شده'}
    return {w for w in re.findall(r'[^\W_]+', text, flags=re.UNICODE) if len(w) >= 3 and w not in stop}


class ChatMemory:
    """Rebuildable local projection: the original JSONL remains the only durable source.
    A turn is a recorded report, never a verified observation. No automatic truth promotion.
    """
    def __init__(self, path, engine_factory, guard_factory, decode_record=None, line_digests=None):
        self.path = Path(path)
        self.engine_factory = engine_factory
        self.guard_factory = guard_factory
        self.decode_record = decode_record
        self.line_digests = line_digests
        self.engine = self.guard = None
        self.records = {}
        self.raw_digest = None

    def refresh(self):
        if not self.path.exists():
            raw = b''
        else:
            with self.path.open('rb') as f:
                raw = f.read(MAX_BYTES + 1)
        if len(raw) > MAX_BYTES or (raw and not raw.endswith(b'\n')):
            raise ValueError('archive bounds or incomplete line')
        digest = sha(raw)
        if self.engine is not None and digest == self.raw_digest:
            return len(self.records)
        engine = self.engine_factory(node_id_version='v2')
        guard = self.guard_factory()
        records = {}
        batch = []
        ids = set()
        for line_no, line in enumerate(raw.splitlines(keepends=True), 1):
            if line_no > MAX_ROWS or len(line) > MAX_LINE:
                raise ValueError('archive line budget')
            clean = line.strip(b' \t\r\n')
            if not clean:
                raise ValueError('blank archive record')
            text = clean.decode('utf-8-sig' if line_no == 1 else 'utf-8')
            row = self.decode_record(text) if self.decode_record else json.loads(text, object_pairs_hook=unique, parse_constant=reject_constant)
            if not isinstance(row, dict) or row.get('record_version') != '15.3':
                raise ValueError('unsupported archive schema')
            rid = row.get('record_id')
            if not isinstance(rid, str) or not rid.strip() or rid in ids:
                raise ValueError('invalid or duplicate record ID')
            ids.add(rid)
            if isinstance(row.get('user'), str) and isinstance(row.get('ario'), str):
                fields = ('user', 'ario')
            elif isinstance(row.get('content'), str):
                fields = ('content',)
            else:
                raise ValueError('unsupported archive record')
            for k in fields:
                if sha(row[k].encode('utf-8')) != row.get(k + '_sha256'):
                    raise ValueError('record text digest mismatch')
            if fields == ('user','ario') and sha((row['user'] + '\n' + row['ario']).encode('utf-8')) != row.get('event_sha256'):
                raise ValueError('paired event digest mismatch')
            # Exact historical line digest, compatible with the legacy trimmed-line policy.
            event_hash = self.line_digests(line)[0] if self.line_digests else sha(clean)
            quote = {'record_id': rid, 'source_line': line_no, 'source_sha256': event_hash, 'status': 'RECORDED', 'source_type': 'LEDGER_REPORT', 'veracity': 'REPORTED_UNVERIFIED', 'timestamp': str(row.get('timestamp',''))[:100]}
            quote.update({k: row[k] for k in fields})
            assertion = json.dumps(quote, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
            attribution = guard.record_unverified_ledger_report(assertion=assertion, record_sha256=event_hash)
            batch.append((event_hash, {'concept': 'conversation:' + rid, 'assertion': assertion, 'status': 'RECORDED', 'attribution_id': attribution.attribution_id}))
            records[event_hash] = quote
            if len(batch) == 256:
                engine.ingest_event_stream(batch); batch = []
        if batch:
            engine.ingest_event_stream(batch)
        if not engine.validate_lineage_integrity():
            raise ValueError('lineage validation failed')
        # Publish only a fully built candidate. No partial replay becomes active.
        self.engine, self.guard, self.records, self.raw_digest = engine, guard, records, digest
        return len(records)

    def recall(self, query):
        if self.engine is None:
            return []
        q = words(query)
        if not q:
            return []
        ranked = []
        for n in self.engine.retrieve_active_context():
            if n.status.value != 'RECORDED':
                continue
            for h in n.source_event_hashes:
                r = self.records.get(h)
                if r is None or is_runtime_error(r.get('ario')) or is_prospective_command(r.get('user', '')):
                    continue
                score = len(q & words(r.get('user', r.get('content',''))))
                if score:
                    ranked.append((score, bool(explicit_statement(r.get('user'))), r['source_line'], r))
        minimum_overlap = 1 if current_assessment(query) else min(2, len(q))
        ranked.sort(key=lambda x: (x[1] and x[0] >= minimum_overlap, x[0], x[1], x[2]), reverse=True)
        return [{k: (v[:MAX_QUOTE] if k in ('user','ario','content') else v) for k,v in r.items()} for _,_,_,r in ranked[:MAX_RESULTS]]


    def recorded_origin(self, subject):
        """Find explicit user declarations with matching topic in the checked projection.

        Only positive, direct recorded-user evidence qualifies; model replies,
        later questions, and content-only records are not proof of origin.
        The result does not establish an upstream or externally verified source.
        """
        terms, requires_name = subject
        if self.engine is None or not terms:
            return []
        hits = {}
        for node in self.engine.retrieve_active_context():
            if node.status.value != 'RECORDED':
                continue
            for digest in node.source_event_hashes:
                row = self.records.get(digest)
                if not row or is_runtime_error(row.get('ario')):
                    continue
                declared = explicit_statement(row.get('user'))
                if not declared or not terms <= words(declared):
                    continue
                if requires_name and not NAME_CUE.search(declared):
                    continue
                hits[digest] = row
        return sorted(hits.values(), key=lambda row: row['source_line'])


# V0.7 integration: use the existing core classes, not another memory engine.
# The working buffer is a per-request, provenance-checked view of durable LTM.
# No eviction/flush writes back to LTM: the archive is already the durable source.
def working_focus(memory, rows, buffer_factory):
    buffer = buffer_factory(capacity=MAX_RESULTS, source_guard=memory.guard)
    if rows:
        canonical = memory.guard.attributions
        for index, row in enumerate(rows[:MAX_RESULTS]):
            digest = row['source_sha256']
            stored = memory.records.get(digest)
            if stored is None or stored['record_id'] != row['record_id']:
                raise ValueError('working memory source not present in replay')
            attr = canonical.get('ATTR-LEDGER-' + digest.lower())
            if attr is None:
                raise ValueError('working memory attribution missing')
            assertion = json.dumps(stored, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
            if attr.assertion != assertion:
                raise ValueError('working memory assertion mismatch')
            buffer.ingest(concept='conversation:' + stored['record_id'], assertion=assertion,
                          source_attribution=attr, salience=0.9 - index * 0.1,
                          metadata={'source_sha256': digest})
    # Consume the buffer's actual admitted chunks, preserving previous ranking.
    by_digest = {r['source_sha256']: r for r in rows}
    selected = []
    for chunk in buffer.active_chunks:
        digest = chunk.metadata['source_sha256']
        row = by_digest[digest]
        if chunk.source_attribution.attribution_id != 'ATTR-LEDGER-' + digest.lower():
            raise ValueError('working memory attribution mismatch')
        selected.append(row)
    assessment = buffer.metacognitive_assessment()
    print(f'[working memory: {buffer.active_count}/{MAX_RESULTS}; '
          f'{assessment.verdict.value}; empirical_ratio={assessment.empirical_ratio:.2f}]',
          file=sys.stderr, flush=True)
    return selected


# Prospective memory: explicit live commands only, no historical replay or model actions.
# Local cues are user reports, not authenticated real-world observations. A trigger
# may display a reminder in this chat; it never runs the reminder as an instruction.
PROSPECTIVE_TTL = 7 * 24 * 60 * 60
MAX_INTENTIONS = 200
MAX_JOURNAL_BYTES = 512 * 1024
CUE = re.compile(r'[A-Za-z0-9][A-Za-z0-9_-]{0,47}\Z')
COMMANDS = frozenset(('/remind-when', '/cue', '/intentions', '/cancel-intention'))
INTENTION_ID = re.compile(r'INT-[0-9a-f]{32}\Z')


def is_prospective_command(text):
    return isinstance(text, str) and bool(text.strip()) and text.strip().split(maxsplit=1)[0].lower() in COMMANDS


def cue_predicate(cue):
    if not CUE.fullmatch(cue):
        raise ValueError('cue must be a single ASCII token (letters, digits, hyphen or underscore)')
    return 'cue == ' + repr(cue)


class ChatProspective:
    """Adapter around the merged registry and its existing atomic journal API.

    Single-user local chat. Journal checksum is local integrity only, not a
    freshness, authenticity or anti-rollback guarantee. No external actions.
    """
    def __init__(self, path, factory, clock=time.time):
        self.path = Path(path)
        self.factory = factory
        self.clock = clock

    def load(self):
        if not self.path.exists():
            return self.factory(max_pending=50)
        if not self.path.is_file() or self.path.stat().st_size > MAX_JOURNAL_BYTES:
            raise ValueError('prospective journal size/type invalid')
        registry = self.factory.load_journal(self.path, max_pending=50, enforce_ast_revalidation=True)
        intentions = registry.intentions
        if len(intentions) > MAX_INTENTIONS:
            raise ValueError('prospective journal capacity exceeded')
        for iid, intent in intentions.items():
            payload = intent.action_payload
            if (not INTENTION_ID.fullmatch(iid) or not isinstance(payload, dict)
                or set(payload) != {'kind', 'cue', 'text'} or payload['kind'] != 'CHAT_REMINDER'
                or not isinstance(payload['cue'], str) or not isinstance(payload['text'], str)
                or not (1 <= len(payload['text']) <= 500)
                or intent.description != payload['text']
                or intent.predicate_expr != cue_predicate(payload['cue'])
                or not isinstance(intent.source_attribution_id, str)
                or not intent.source_attribution_id.startswith('LOCAL-USER-COMMAND:')
                or not all(math.isfinite(x) for x in (intent.created_at_epoch, intent.ttl_epoch))
                or intent.ttl_epoch - intent.created_at_epoch != PROSPECTIVE_TTL):
                raise ValueError('prospective journal contains an out-of-scope intention')
        return registry

    def handle(self, text):
        parts = text.strip().split(maxsplit=1)
        command = parts[0].lower()
        rest = parts[1].strip() if len(parts) == 2 else ''
        if command not in COMMANDS:
            raise ValueError('unknown prospective command')
        # Validate input before journal mutation. Never interpret a reminder as code.
        if command == '/remind-when':
            cue, sep, message = rest.partition('|')
            cue, message = cue.strip(), message.strip()
            if not sep or not (1 <= len(message) <= 500) or any(ord(c) < 32 for c in message):
                raise ValueError('usage: /remind-when CUE | reminder text (1..500 chars)')
            predicate = cue_predicate(cue)
        elif command == '/cue':
            cue = rest
            cue_predicate(cue)
        elif command == '/cancel-intention':
            if not INTENTION_ID.fullmatch(rest):
                raise ValueError('usage: /cancel-intention INT-...')
        elif rest:
            raise ValueError('usage: /intentions')
        now = self.clock()
        if not math.isfinite(now):
            raise ValueError('local clock is invalid')
        now = int(now)
        registry = self.load()
        expired = registry.reconcile_expired_intentions(now)
        changed = bool(expired)
        if command == '/remind-when':
            if len(registry.intentions) >= MAX_INTENTIONS:
                raise ValueError('prospective journal full; no intention deleted')
            iid = 'INT-' + uuid.uuid4().hex
            registry.register_intention(description=message, predicate_expr=predicate,
                action_payload={'kind':'CHAT_REMINDER','cue':cue,'text':message},
                created_at_epoch=now, ttl_epoch=now + PROSPECTIVE_TTL,
                intention_id=iid, source_attribution_id='LOCAL-USER-COMMAND:' + sha(text.encode('utf-8')))
            changed = True
            reply = f'Reminder recorded as PENDING ({iid}). Cue: {cue}. Expires in 7 days; chat-only.'
        elif command == '/cue':
            # This context comes only from the current user command, never old JSONL.
            triggered = registry.evaluate_cues({'cue': cue}, current_epoch=now)
            changed |= bool(triggered)
            reply = ('\n'.join(f'Reminder ({i.intention_id}): {i.action_payload["text"]}' for i in triggered)
                     if triggered else 'No pending reminder matched this reported cue.')
        elif command == '/cancel-intention':
            registry.cancel_intention(rest)
            changed = True
            reply = f'Cancelled reminder {rest}; its record is retained.'
        else:
            reply = ('\n'.join(f'{i.intention_id}: {i.status.value} | {i.description}'
                               for i in registry.intentions.values()) or 'No reminders registered.')
        # Save before reporting success. Core owns the journal serialization and atomic replacement.
        if changed:
            registry.save_journal(self.path)
        print(f'[prospective memory: {command}; pending={len(registry.get_pending_intentions())}; chat-only]',
              file=sys.stderr, flush=True)
        return reply


def local_chat(mod, prompt, records):
    parsed = urllib.parse.urlsplit(mod.OLLAMA_URL)
    if parsed.scheme != 'http' or parsed.hostname not in ('localhost','127.0.0.1','::1') or parsed.username or parsed.password:
        raise ValueError('Ollama must be local')
    # Resolve localhost to numeric loopback and refuse proxy/redirect transport.
    port = parsed.port or 11434
    host = '[::1]' if parsed.hostname == '::1' else '127.0.0.1'
    class NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self,*args,**kwargs):
            raise ValueError('Ollama redirect refused')
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())
    # The old multi-layer prompt mixes earlier answers and current instructions.
    # Use one bounded set of quoted records and one actual current question.
    config = []
    for key, limit in (('IDENTITY', 1000), ('PRINCIPLES', 1200)):
        path = getattr(mod, key, None)
        if path is not None:
            try:
                with Path(path).open('r', encoding='utf-8-sig') as f:
                    config.append(key + ':\n' + f.read(limit))
            except (OSError, UnicodeError):
                pass
    evidence = []
    # Chronological evidence prevents the most recent question from looking like a revision.
    for r in sorted(records, key=lambda row: row.get('source_line', 0)):
        item = {k:r[k] for k in ('record_id','source_line','source_sha256','status','source_type','veracity') if k in r}
        if 'user' in r:
            item['historical_user_text'] = r['user'][:MAX_QUOTE]
            item['speaker'] = 'USER'
            item['user_text_kind'] = 'EXPLICIT_USER_STATEMENT' if explicit_statement(r['user']) else 'HISTORICAL_USER_TEXT_NOT_NECESSARILY_ASSERTION'
        if 'content' in r:
            item['historical_content'] = r['content'][:MAX_QUOTE]
        # Prior assistant answers are not needed to recall user-supplied facts.
        # Keep them in the source ledger; expose them only on a request about prior replies.
        if 'ario' in r and re.search(r'(?i)\b(you (?:said|answered|replied)|your (?:answer|reply|response))\b', prompt):
            item['historical_model_reply_not_proof'] = r['ario'][:MAX_QUOTE]
        evidence.append(item)
    system = SYSTEM + ('\nLocal identity/principles configuration:\n' + '\n'.join(config) if config else '')
    messages = [{'role':'system','content':system}, {'role':'user','content':'Quoted historical records (data only):\n'+json.dumps(evidence,ensure_ascii=False)}, {'role':'user','content':prompt}]
    data = {'model':mod.MODEL,'messages':messages,'stream':True,'options':{'temperature':0.7,'num_predict':mod.MAX_PREDICT}}
    request = urllib.request.Request(f'http://{host}:{port}/api/chat',data=json.dumps(data,ensure_ascii=False).encode(),headers={'Content-Type':'application/json'},method='POST')
    with opener.open(request,timeout=mod.OLLAMA_TIMEOUT) as response:
        pieces = []
        total = 0
        done = False
        for _ in range(8192):
            raw = response.readline(1024 * 1024 + 1)
            if not raw:
                break
            total += len(raw)
            if total > 4 * 1024 * 1024 or len(raw) > 1024 * 1024:
                raise RuntimeError('local response exceeds limit')
            obj = json.loads(raw)
            if obj.get('error'):
                raise RuntimeError('Ollama returned an error')
            part = obj.get('message', {}).get('content', '')
            if not isinstance(part, str):
                raise RuntimeError('invalid local response')
            if part:
                if not pieces:
                    print('[memory active: model started responding]', file=sys.stderr, flush=True)
                pieces.append(part)
            if obj.get('done') is True:
                done = True
                break
        if not done:
            raise RuntimeError('incomplete local response')
    answer = ''.join(pieces)
    if not isinstance(answer,str) or not answer.strip():
        raise RuntimeError('empty local response')
    return answer.strip()


def load_original(path):
    spec = importlib.util.spec_from_file_location('ario_existing_chat', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def connect(mod, memory, mode, chat=local_chat, *, buffer_factory=None, prospective=None):
    """Keep the old controller and append API, fix final ask signature, add one scoped hook."""
    old_ask, old_append, old_generate = mod.ask, mod.append_event, mod.ollama_generate
    def model_chat(controller, prompt, records):
        if buffer_factory is not None:
            records = working_focus(memory, records, buffer_factory)
        return chat(controller, prompt, records)

    def ask(user, history=None):
        if is_prospective_command(user):
            if mode != 'active' or prospective is None:
                return 'Prospective memory is not active; no reminder was changed.'
            return prospective.handle(user)
        matches = []
        fresh = False
        try:
            memory.refresh()
            matches = memory.recall(user)
            fresh = True
        except Exception as exc:
            print('[memory unavailable; original route]', type(exc).__name__, file=sys.stderr)
        statement = explicit_statement(user)
        if mode == 'active' and statement is not None:
            print('[memory active: explicit user statement; recorded on append]', file=sys.stderr)
            return 'I will record your statement as user-provided information, not an independently verified fact.'
        subject = origin_subject(user)
        if mode == 'active' and subject is not None and not mod.v161_is_trajectory_query(user):
            origins = memory.recorded_origin(subject) if fresh else []
            print(f'[memory active: recorded source attribution; matches={len(origins)}]', file=sys.stderr)
            if not origins:
                return 'The original supplier is unknown from the available matching explicit user records; I cannot infer an external source.'
            refs = ', '.join(json.dumps(r['record_id'], ensure_ascii=True) for r in origins[:2])
            return (f'The user supplied the information in the matching recorded statements (record IDs: {refs}); '
                    'any earlier or independent external origin is unknown.')
        assessment = current_assessment(user)
        historical = mod.v1547_is_historical_query(user)
        trajectory = mod.v161_is_trajectory_query(user)
        # Preserve Python-owned earliest-history and causal/trajectory controllers.
        # A scoped recall with relevant explicit user reports is not an unsupported
        # historical claim; route directly rather than invoking the old refusal.
        deterministic = None
        if mode == 'active' and historical and matches:
            deterministic = mod.v1542_deterministic_history_answer(user)
        if deterministic is not None:
            return deterministic
        query_terms = words(user)
        explicit_hits = [r for r in matches if explicit_statement(r.get('user'))
                         and query_terms and len(query_terms & words(r['user'])) >= min(2, len(query_terms))]
        scoped_history = (historical or temporal_comparison(user)) and not trajectory and bool(explicit_hits)
        if mode == 'active' and (scoped_history or (assessment and not trajectory)):
            route = 'current evidence assessment' if assessment else 'scoped history'
            print(f'[memory active: {len(matches)} candidate(s); eligible=True; {route}]', file=sys.stderr)
            try:
                answer = model_chat(mod, user, matches)
            except Exception as exc:
                print('[memory active failed; no retry]', type(exc).__name__, file=sys.stderr)
                raise RuntimeError('Ollama generation failed; no conversation archived: ' + type(exc).__name__) from exc
            if not isinstance(answer, str) or not answer.strip() or is_runtime_error(answer):
                raise RuntimeError('Invalid model response; no conversation archived')
            print('[memory active: local chat response received]', file=sys.stderr)
            return answer
        normal = not (historical or trajectory)
        print(f'[memory {mode}: {len(matches)} candidate(s); eligible={mode == "active" and normal and bool(matches)}]', file=sys.stderr)
        used = False
        failure = None
        def generate(prompt):
            nonlocal used, failure
            if failure is not None:
                raise RuntimeError("generation already failed; no retry") from failure
            if mode == 'active' and normal and matches and not used:
                used = True
                try:
                    answer = model_chat(mod, user, matches)
                    print('[memory active: local chat response received]', file=sys.stderr)
                    return answer
                except Exception as exc:
                    failure = exc
                    print('[memory active failed; no retry]', type(exc).__name__, file=sys.stderr)
                    raise
            try:
                return old_generate(prompt)
            except Exception as exc:
                failure = exc
                raise
        mod.ollama_generate = generate
        try:
            answer = old_ask(user)
            if failure is not None:
                raise RuntimeError("Ollama generation failed; no conversation archived: " + type(failure).__name__) from failure
            if is_runtime_error(answer):
                raise RuntimeError("Controller generation failed; no conversation archived")
            if isinstance(answer, dict) and answer.get('route') == 'LINEAGE':
                # The newer uploaded controller returns a dict on this route, but append_event expects str.
                return 'Historical lineage context (not independently verified):\n' + json.dumps(answer.get('context'), ensure_ascii=False, default=str)[:8000]
            if not isinstance(answer, str):
                raise TypeError('Unsupported controller response')
            return answer
        finally:
            mod.ollama_generate = old_generate
    def append(user, answer):
        if is_runtime_error(answer):
            raise RuntimeError("Refusing to archive runtime error as conversation")
        event = old_append(user, answer)
        try:
            memory.refresh()
        except Exception as exc:
            print('[archive appended; memory refresh deferred]', type(exc).__name__, file=sys.stderr)
        return event
    mod.ask, mod.append_event = ask, append
    return mod


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--mode',choices=('shadow','active'),default='shadow')
    parser.add_argument('--repo',help='local checkout at pinned commit')
    parser.add_argument('--install-core',action='store_true',help='download pinned public core files only')
    parser.add_argument('--original',type=Path,help='optional path to the exact installed chat loop')
    parser.add_argument('--port',type=int,default=11434)
    parser.add_argument('--model')
    parser.add_argument('--max-predict',type=int,default=128)
    parser.add_argument('--timeout',type=int,default=180)
    parser.add_argument('--check',action='store_true',help='replay current archive without writing or calling Ollama')
    args = parser.parse_args()
    if not 1 <= args.max_predict <= 2048 or not 5 <= args.timeout <= 600:
        parser.error("max-predict must be 1..2048 and timeout 5..600 seconds")
    engine, guard, decoder, digests, buffer, registry = load_core(args.repo,args.install_core)
    import tempfile
    # Verify the real pinned core against an isolated, source-shaped turn before opening live data.
    with tempfile.TemporaryDirectory() as tmp:
        fixture = Path(tmp)/'archive.jsonl'
        user, reply = 'bicycle smoke test', 'historical answer'
        row = {'record_version':'15.3','record_id':'smoke-1','user':user,'ario':reply,
               'user_sha256':sha(user.encode()),'ario_sha256':sha(reply.encode()),
               'event_sha256':sha((user+'\n'+reply).encode())}
        fixture.write_text(json.dumps(row)+'\n',encoding='utf-8')
        probe=ChatMemory(fixture,engine,guard,decoder,digests)
        if probe.refresh()!=1 or probe.recall('bicycle')[0]['record_id']!='smoke-1' or probe.recall('unrelated'):
            raise RuntimeError('Pinned core integration smoke test failed')
        print('Pinned core replay / retrieval smoke test: PASS')
        focused = working_focus(probe, probe.recall('bicycle'), buffer)
        if len(focused) != 1 or focused[0]['record_id'] != 'smoke-1':
            raise RuntimeError('Pinned working memory smoke test failed')
        journal = Path(tmp)/'prospective.json'
        pm = ChatProspective(journal, registry, clock=lambda: 1000.0)
        if 'PENDING' not in pm.handle('/remind-when test-cue | smoke reminder'):
            raise RuntimeError('Pinned prospective registration smoke test failed')
        pm = ChatProspective(journal, registry, clock=lambda: 1001.0)
        if 'No pending' not in pm.handle('/cue unrelated-cue'):
            raise RuntimeError('Pinned prospective wrong-cue smoke test failed')
        if 'smoke reminder' not in pm.handle('/cue test-cue') or 'No pending' not in pm.handle('/cue test-cue'):
            raise RuntimeError('Pinned prospective restart/trigger smoke test failed')
        pm.handle('/remind-when cancel-cue | cancelled smoke reminder')
        pending = pm.load().get_pending_intentions()
        if len(pending) != 1:
            raise RuntimeError('Pinned prospective pending smoke test failed')
        pm.handle('/cancel-intention ' + pending[0].intention_id)
        if 'No pending' not in pm.handle('/cue cancel-cue'):
            raise RuntimeError('Pinned prospective cancel smoke test failed')
        pm.handle('/remind-when expire-cue | expired smoke reminder')
        later = ChatProspective(journal, registry, clock=lambda: 1001.0 + PROSPECTIVE_TTL)
        if 'No pending' not in later.handle('/cue expire-cue') or 'EXPIRED' not in later.handle('/intentions'):
            raise RuntimeError('Pinned prospective expiry smoke test failed')
        print('Pinned working / prospective memory smoke tests: PASS')
    if args.original:
        original=args.original.resolve()
        sys.path.insert(0,str(original.parent))
    else:
        # Prefer the newer causal/lineage version only if its existing dependency is present.
        sys.path.insert(0,str(Path.home()/'QwenMemory'))
        original = ROOT/('ario_original_lineage.py' if importlib.util.find_spec('ario_lineage_adapter_v0_3') else 'ario_original.py')
    print('Ario Live Memory v' + VERSION)
    print('Original controller:', original.name)
