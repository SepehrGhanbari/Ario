REMEMBER = re.compile(r'(?i)(?:^|[,.!;]\s*)\s*(?:please\s+)?remember\s+that\s+([^?\n]+)\s*$')

# Recognize bounded, declarative changes as user reports, not verified facts.
REVISION = re.compile(r'(?i)^(?:the\s+|our\s+|my\s+)?[^?\n.!;]{1,250}\s+(?:has\s+been\s+|was\s+|is\s+)?(?:renamed|changed|updated|revised|switched)\s+from\s+[^?\n]+?\s+to\s+[^?\n]+$')
COMPARISON = re.compile(r'(?i)\b(?:current|now|new|latest)\b')
PAST = re.compile(r'(?i)\b(?:previous|old|former|original|before|prior)\b')


def explicit_statement(text):
    if not isinstance(text, str) or '?' in text:
        return None
    m = REMEMBER.search(text.strip())
    if m:
        return m.group(1).strip()
    if REVISION.fullmatch(text.strip()):
        return text.strip()
    return None

def temporal_comparison(text):
    return bool(COMPARISON.search(text) and PAST.search(text))
# Present-tense assessment is distinct from retrieval of a historical event.
# Require both an assessment cue and an evidence/memory cue; no subject-specific rules.
ASSESSMENT = re.compile(r"(?i)\b(?:do you agree|would you agree|is (?:that|this|it) (?:true|proven|verified|sufficient|evidence)|does .{1,160}? (?:prove|establish|constitute|count as|confirm)|can .{1,160}? (?:prove|establish|confirm|verify)|(?:is|are) .{1,160}? (?:proven|verified|independent evidence)|why (?:is|does|do|isn.t))\b")
EVIDENCE_CUE = re.compile(r"(?i)\b(?:evidence|proof|prove|proven|verified|verify|verification|scientifically|remember|memory|repetition|repeated|remembered|corroborat\w*)\b")


def current_assessment(text):
    return bool(ASSESSMENT.search(text) and EVIDENCE_CUE.search(text))

# Direct, single-question provenance requests are answered from recorded roles,
# not generated by the language model. This identifies the recorded speaker,
# not the ultimate origin of a claim or independent authentication of it.
ORIGIN_QUESTION = re.compile(
    r"(?i)^\s*who\s+(?:(?:originally|first|actually)\s+)?"
    r"(?:supplied|provided|reported|stated|gave|introduced)\s+([^?:\n]+)"
    r"(?:\s*:\s*(?:the\s+)?user\s*,\s*ario\s*,?\s*or\s+(?:an?\s+)?external source)?"
    r"\s*\?\s*(?:answer in one sentence\.?)?\s*$"
)
ORIGIN_GENERIC = {'information','detail','details','claim','claims','statement','statements',
                  'name','names','data','record','records','source','sources','originally',
                  'supplied','provided','reported','stated','gave','introduced','who','the',
                  'user','ario','external'}
NAME_CUE = re.compile(r'(?i)\b(?:name|names|named|renamed)\b')


def origin_subject(query):
    match = ORIGIN_QUESTION.fullmatch(query)
    if not match:
        return None
    subject = match.group(1).strip()
    # Compound queries are outside this bounded deterministic route.
    if re.search(r'(?i)\b(?:and|or)\s+(?:do|does|did|is|are|what|who|why|how|can)\b', subject):
        return None
    return words(subject) - ORIGIN_GENERIC, bool(NAME_CUE.search(subject))


