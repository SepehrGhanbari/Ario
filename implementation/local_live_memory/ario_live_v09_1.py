REMEMBER = re.compile(r'(?i)(?:^|[,.!;]\s*)\s*(?:please\s+)?remember\s+that\s+([^?\n]+)\s*$')

# Recognize bounded, declarative changes as user reports, not verified facts.
REVISION = re.compile(r'(?i)^(?:the\s+|our\s+|my\s+)?[^?\n.!;]{1,250}\s+(?:has\s+been\s+|was\s+|is\s+)?(?:renamed|changed|updated|revised|switched)\s+from\s+[^?\n]+?\s+to\s+[^?\n]+$')
