def blob_id(raw):
    return hashlib.sha1(f'blob {len(raw)}\0'.encode() + raw).hexdigest()


def load_core(repo=None, install=False):
    """Use a verified local checkout or retrieve seven pinned public source files."""
    vendor = ROOT / 'vendor' / 'core'
    source = Path(repo).resolve() / 'implementation' / 'core' if repo else vendor
    if source != vendor or install:
        vendor.mkdir(parents=True, exist_ok=True)
        for name, pin in BLOBS.items():
            target = vendor / name
            if source == vendor and target.is_file() and blob_id(target.read_bytes()) == pin:
                continue
            if source != vendor:
                raw = (source / name).read_bytes()
            else:
                url = f'https://raw.githubusercontent.com/SepehrGhanbari/Ario/{PIN}/implementation/core/{name}'
                with urllib.request.urlopen(url, timeout=30) as f:
                    raw = f.read(1024 * 1024 + 1)
            if len(raw) > 1024 * 1024 or blob_id(raw) != pin:
                raise RuntimeError(f'Pinned upstream file mismatch: {name}')
            target.write_bytes(raw)
    for name, pin in BLOBS.items():
        if blob_id((vendor / name).read_bytes()) != pin:
            raise RuntimeError(f'Pinned core mismatch: {name}')
    # No preexisting unrelated `core` package can be substituted.
    if any(n == 'core' or n.startswith('core.') for n in sys.modules):
        raise RuntimeError('core already imported; start a fresh process')
    spec = importlib.util.spec_from_loader('core', loader=None, is_package=True)
    import types
    pkg = types.ModuleType('core')
    pkg.__spec__ = spec
    pkg.__path__ = [str(vendor)]
    sys.modules['core'] = pkg
