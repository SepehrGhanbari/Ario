    def test_07_redirect_target_was_not_contacted(self):
        # A reachable sink detects attempted redirect-follow, not just a failed
        # connection to an unavailable address. Sink is disposable loopback.
        import threading
        from http.server import BaseHTTPRequestHandler,ThreadingHTTPServer
        from w22_tile_server import make_server
        from copy import deepcopy
        hits=[]
        class Sink(BaseHTTPRequestHandler):
            def do_GET(self):
                hits.append(self.path)
                self.send_response(200)
                self.send_header('Content-Type','text/plain; charset=utf-8')
                self.end_headers()
                self.wfile.write(LATEST)
            def log_message(self,*args):pass
        sink=ThreadingHTTPServer(('127.0.0.1',0),Sink)
        test_fixture=deepcopy(FIXTURE)
        test_fixture['_redirect_target']=f'http://127.0.0.1:{sink.server_port}/checkpoint'
        redirector=make_server(test_fixture,'redirect')
        s1=threading.Thread(target=sink.serve_forever,daemon=True)
        s2=threading.Thread(target=redirector.serve_forever,daemon=True)
        s1.start();s2.start()
        try:
            base=f'http://127.0.0.1:{redirector.server_port}'
            out=observe(base,pinned_vkey=VKEY,retained_prior=PRIOR,retained_highwater=LATEST)
            self.assertEqual((out['verdict'],out['reason']),('HOLD_UNCERTAIN','NETWORK_OR_WIRE_ERROR'))
            self.assertEqual(hits,[],'SECURITY FAILURE: secondary endpoint was contacted')
        finally:
            redirector.shutdown();sink.shutdown();redirector.server_close();sink.server_close()
            s1.join(timeout=3);s2.join(timeout=3)

