HERE=Path(__file__).parent
PUBLISHED=HERE/'W22_PUBLIC_SYNTHETIC_SIGNED_NOTES_2026-11-17.json'
W20=HERE/'W20_SYNTHETIC_LOG_CHECKPOINTS_AND_PROOFS_2026-11-17.json'
FIXTURE=json.loads(PUBLISHED.read_text('utf8'))
VKEY=FIXTURE['public_vkey_for_synthetic_demo_only']
PRIOR=FIXTURE['previous_checkpoint'].encode()
LATEST=FIXTURE['current_checkpoint'].encode()
FORK=FIXTURE['same_signer_fork_checkpoint'].encode()


def spawn_server(mode):
    p=subprocess.Popen([sys.executable,'-u',str(HERE/'w22_tile_server.py'),'--fixture',str(PUBLISHED),
                        '--w20-fixture',str(W20),'--mode',mode],stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True)
    r,_,_=select.select([p.stdout],[],[],5)
    if not r:
        p.kill();err=p.stderr.read();p.wait(timeout=3)
        raise RuntimeError('no ready stdout from server: '+err[:800])
    line=p.stdout.readline().strip()
    if not line.startswith('W22_LOOPBACK_READY http://127.0.0.1:'):
        p.kill();p.wait(timeout=3);raise RuntimeError('unexpected status: '+line)
    return p,line.split(' ',1)[1]


class W22(unittest.TestCase):
    def test_01_note_grammar_and_independent_verifier(self):
        old=verify_note(PRIOR,VKEY); new=verify_note(LATEST,VKEY)
        self.assertEqual((old['size'],new['size']),(3,8))
        self.assertEqual(old['origin'],FIXTURE['origin'])
        self.assertNotEqual(old['root'],new['root'])
        self.assertIsNotNone(verify_note(FORK,VKEY))  # actual SAME signer fork
        self.assertIsNone(verify_note(LATEST.replace(b'\n8\n',b'\n08\n'),VKEY))
        self.assertIsNone(verify_note(LATEST+b'\n',VKEY))
        self.assertIsNone(verify_note(LATEST+b'junk',VKEY))
        self.assertIsNone(verify_note(LATEST,VKEY.replace('+','-',1)))
        self.assertIsNone(verify_note(LATEST,VKEY[:-1]+'A'))
        # A valid public key with *wrong signature key ID* must not parse.
        name,keyid,keymat=VKEY.split('+')
        forged_id=('0' if keyid[0]!='0' else '1')+keyid[1:]
        self.assertIsNone(verify_note(LATEST,name+'+'+forged_id+'+'+keymat))
        self.assertIsNone(verify_note(LATEST.replace(b'\n\n',b'\n\nextra\n',1),VKEY))
        # A syntactically correct but cryptographically different signature must fail.
        import base64
        note_text,sign_line=LATEST.split(b'\n\n')
        prefix=('— '+FIXTURE['origin']+' ').encode()
        self.assertTrue(sign_line.startswith(prefix))
        sig=bytearray(base64.b64decode(sign_line[len(prefix):].strip()))
        sig[-1]^=1
        forged=note_text+b'\n\n'+prefix+base64.b64encode(sig)+b'\n'
        self.assertIsNone(verify_note(forged,VKEY))

    def test_02_official_c2sp_vkey_example(self):
        # Exact known C2SP signed-note official example (not generated by W22).
        import base64,hashlib
        vkey='example.com/foo+530d903a+AekyeRrm56hApGFkyQR4ZCbV54Id2LKaANYcrnKv3U2k'
        name,key_id,b64pub=vkey.split('+')
        data=base64.b64decode(b64pub,validate=True)
        self.assertEqual(len(data),33)
        self.assertEqual(data[0],1)
        self.assertEqual(hashlib.sha256(name.encode()+b'\n\x01'+data[1:]).digest()[:4].hex(),key_id)

    def test_03_valid_partial_tiles_and_continuity(self):
        process,base=spawn_server('normal')
        try:
            z=observe(base,pinned_vkey=VKEY,retained_prior=PRIOR,retained_highwater=LATEST)
            self.assertEqual((z['verdict'],z['read_only_preview'] ),('HISTORICAL_CONSISTENT',True),z)
            self.assertEqual(z['operational_authority'],'NONE')
            self.assertEqual(z['latest_world_state'],'UNKNOWN')
            with urlopen(base+'/checkpoint',timeout=2) as r:
                self.assertEqual(r.headers.get_content_type(),'text/plain')
                self.assertEqual(r.read(),LATEST)
            with urlopen(base+'/tile/0/0.p/8',timeout=2) as r:
                self.assertEqual((r.headers.get_content_type(),len(r.read())),('application/octet-stream',256))
            with urlopen(base+'/tile/entries/0.p/8',timeout=2) as r:
                self.assertEqual(r.headers.get_content_type(),'application/octet-stream')
                self.assertGreater(len(r.read()),100)
            with self.assertRaises(HTTPError) as ctx:
                urlopen(Request(base+'/checkpoint',method='POST'),timeout=2)
            self.assertEqual(ctx.exception.code,405)
            self.assertIsNone(process.poll())
        finally:
            process.terminate();process.wait(timeout=4); process.stdout.close(); process.stderr.close()

