    def test_05_wrong_trust_inputs_hold(self):
        process,base=spawn_server('normal')
        try:
            for kwargs,reason in [
                ({'pinned_vkey':None,'retained_prior':PRIOR,'retained_highwater':LATEST},'NO_OUT_OF_BAND_VKEY'),
                ({'pinned_vkey':VKEY,'retained_prior':None,'retained_highwater':LATEST},'NO_RETAINED_PRIOR'),
                ({'pinned_vkey':VKEY,'retained_prior':PRIOR,'retained_highwater':None},'NO_RETAINED_HIGHWATER'),
                ({'pinned_vkey':'other-origin+ffffffff+AQ==','retained_prior':PRIOR,'retained_highwater':LATEST},'PRIOR_SIGNATURE_INVALID'),
            ]:
                z=observe(base,**kwargs)
                self.assertEqual((z['verdict'],z['reason']),('HOLD_UNCERTAIN',reason),z)
            self.assertFalse(allowed_base('https://example.org:443'))
            self.assertFalse(allowed_base('http://127.0.0.1:8888/path'))
            self.assertFalse(allowed_base('http://root@127.0.0.1:8888'))
            # Same signer signed two contradictory size-8 roots: retained trust conflict.
            conflict=observe(base,pinned_vkey=VKEY,retained_prior=LATEST,retained_highwater=FORK)
            self.assertEqual((conflict['verdict'],conflict['reason']),('DENY','PINNED_PRIOR_AND_HIGHWATER_FORK'))
        finally:
            process.terminate();process.wait(timeout=4); process.stdout.close(); process.stderr.close()

